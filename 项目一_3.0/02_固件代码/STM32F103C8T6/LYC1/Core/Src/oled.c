/* 8x16 ASCII 字库（2026-11-14 移出到 oled_cn_font.h 并补全）
 *
 * 原表只有 16 个字符（' ' 到 '/'），而 OLED_ShowChar 用 c = ch - ' ' 索引、
 * 显示 'B'(0x42) 时算出的索引是 34，早就越界读到别的常量了。之前没暴露出
 * 问题，是因为界面清一色用 6x8 小字，F8X16 这条分支一次都没被真正走过。
 *
 * 现在换成 g_ascii8x16[95][16]（0x20~0x7E 全 ASCII），字宽 8 px、字高 16 px，
 * 与 16x16 汉字同高，中英文混排时基线天然对齐。数据见 oled_cn_font.h。
 */

/* 写入命令 */
static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {OLED_CMD, cmd};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 2, OLED_TIMEOUT);
}

/* 写入数据 */
static void OLED_WriteData(uint8_t *data, uint16_t len)
{
    uint8_t buf[129];
    buf[0] = OLED_DATA;
    memcpy(buf + 1, data, len);
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, len + 1, OLED_TIMEOUT);
}

/* ===== 显存 + 差异刷新（2026-11-14 重写，治闪烁）=====
 *
 * 【原来的问题】
 * OLED_Clear() 每帧真的往屏幕写 8 × 128 = 1024 个 0x00。SSD1306 是逐页刷新的，
 * 清屏这 24.8 ms 里整屏可见地变黑，然后再用 22 ms 一页页画回来。
 * 于是每渲染一帧就有一次全屏黑闪：1 Hz 时是"每秒黑一下"，
 * 改成 10 Hz 后就变成持续抖动 —— 刷新越快越明显，方向本来就是错的。
 *
 * 【现在的做法】
 * RAM 里放两块 1 KB：
 *   g_ram = 这一帧想显示的内容。所有画字函数只写它，一个字节 I2C 都不发。
 *   g_on  = 屏幕上此刻真实的内容（上次真正发出去的副本）。
 * 每帧结尾调一次 OLED_Refresh()，逐页比对，只把"变了的列区间"发下去，
 * 没变的页一个字节都不发。
 *
 * 稳态下只有电压、温度那几个数字在变，一帧约 50~150 字节、2~4 ms；
 * 屏幕任何时刻都不会出现黑屏，也就不再有闪烁。
 *
 * 【代价】RAM 2 KB。F103C8 共 20 KB，改前只用了 1.5 KB，放得下。
 */
static uint8_t g_ram[8][128];   /* 想显示什么 */
static uint8_t g_on[8][128];    /* 屏幕上现在是什么 */

/* 光标：OLED_SetPos 只改这两个变量，不再发 I2C。
 * 真正发"设置页/列"命令的是 OLED_PosCmd()，只给刷新函数用。 */
static uint8_t g_cur_page = 0;
static uint8_t g_cur_col  = 0;

/* 真正向 SSD1306 发定位命令（页面寻址模式） */
static void OLED_PosCmd(uint8_t page, uint8_t col)
{
    OLED_WriteCmd((uint8_t)(0xB0 + page));
    OLED_WriteCmd((uint8_t)(((col & 0xF0) >> 4) | 0x10));
    OLED_WriteCmd((uint8_t)(col & 0x0F));
}

/* 设置光标位置（只改 RAM 里的光标，不碰屏幕） */
void OLED_SetPos(uint8_t y, uint8_t x)
{
    g_cur_page = (y > 7)   ? 7   : y;
    g_cur_col  = (x > 127) ? 127 : x;
}

/* 把 len 个字节写进显存，从光标处向右排，越过右边界自动截断。
 * 取代原来的 OLED_WriteData 直接写屏（那个现在是刷新的专用通道）。 */
static void OLED_PutBytes(const uint8_t *data, uint16_t len)
{
    uint16_t i;

    for (i = 0; i < len; i++)
    {
        uint16_t col = (uint16_t)g_cur_col + i;
        if (col >= 128) break;
        g_ram[g_cur_page][col] = data[i];
    }
}

/* 清屏（只清显存，不写屏） */
void OLED_Clear(void)
{
    memset(g_ram, 0x00, sizeof(g_ram));
}

/* 差异刷新：把显存里与屏幕不同的部分发下去。
 * 逐页找"第一列不同"和"最后一列不同"，只发这一段连续区间；
 * 整页都没变就直接跳过。 */
void OLED_Refresh(void)
{
    uint8_t  page, first, last;
    uint16_t n;

    for (page = 0; page < 8; page++)
    {
        for (first = 0; first < 128; first++)
        {
            if (g_ram[page][first] != g_on[page][first]) break;
        }
        if (first == 128) continue;              /* 整页没变，跳过 */

        for (last = 127; last > first; last--)
        {
            if (g_ram[page][last] != g_on[page][last]) break;
        }

        n = (uint16_t)(last - first + 1);
        OLED_PosCmd(page, first);
        OLED_WriteData(&g_ram[page][first], n);
        memcpy(&g_on[page][first], &g_ram[page][first], n);
    }
}

/* OLED初始化 */
void OLED_Init(void)
{
    HAL_Delay(100);
    
    OLED_WriteCmd(0xAE); // 关闭显示
    
    OLED_WriteCmd(0x20); // 设置内存寻址模式
    OLED_WriteCmd(0x10); // 页面寻址模式
    
    OLED_WriteCmd(0xB0); // 设置页地址
    
    OLED_WriteCmd(0xC8); // COM扫描方向
    OLED_WriteCmd(0x00); // 列地址低位
    OLED_WriteCmd(0x10); // 列地址高位
    
    OLED_WriteCmd(0x40); // 设置起始行地址
    
    OLED_WriteCmd(0x81); // 设置对比度
    OLED_WriteCmd(0xFF);
    
    OLED_WriteCmd(0xA1); // 段重映射
    OLED_WriteCmd(0xA6); // 正常显示
    
    OLED_WriteCmd(0xA8); // 多路复用率
    OLED_WriteCmd(0x3F);
    
    OLED_WriteCmd(0xA4); // 显示全部开启
    
    OLED_WriteCmd(0xD3); // 显示偏移
    OLED_WriteCmd(0x00);
    
    OLED_WriteCmd(0xD5); // 显示时钟分频
    OLED_WriteCmd(0xF0);
    
    OLED_WriteCmd(0xD9); // 预充电周期
    OLED_WriteCmd(0x22);
    
    OLED_WriteCmd(0xDA); // COM引脚配置
    OLED_WriteCmd(0x12);
    
    OLED_WriteCmd(0xDB); // VCOMH
    OLED_WriteCmd(0x20);
    
    OLED_WriteCmd(0x8D); // 电荷泵
    OLED_WriteCmd(0x14);
    
    OLED_WriteCmd(0xAF); // 开启显示
    
    /* 上电时屏幕里是随机内容，而 g_on 在 BSS 里是全 0，两者一比对会误判
     * "屏幕已经是黑的了"，结果整屏一个字都不发。所以把 g_on 全填 0xFF
     * （必然与实际不同），强制第一次刷新把整屏写一遍，之后才进入差异刷新。 */
    memset(g_ram, 0x00, sizeof(g_ram));
    memset(g_on,  0xFF, sizeof(g_on));
    OLED_Refresh();
}

/* 显示单个字符（8x16 时占 y、y+1 两页）*/
void OLED_ShowChar(uint8_t y, uint8_t x, char ch, uint8_t font_size)
{
    uint8_t c = 0;

    /* 越界保护：字库只覆盖 0x20~0x7E，其余（含中文、控制符）统一显示空格。
     * 原来没这一步，传入 'B' 之类就会按 c=34 去读只有 16 项的表。 */
    if ((ch < (char)ASCII_FONT_FIRST) || (ch > (char)0x7E))
    {
        ch = ' ';
    }
    c = (uint8_t)(ch - ASCII_FONT_FIRST);

    if (font_size == FONT_6x8)
    {
        OLED_SetPos(y, x);
        OLED_PutBytes((const uint8_t *)F6x8[c], 6);
    }
    else if (font_size == FONT_8x16)
    {
        OLED_SetPos(y, x);
        OLED_PutBytes((const uint8_t *)g_ascii8x16[c], 8);
        OLED_SetPos(y + 1, x);
        OLED_PutBytes((const uint8_t *)g_ascii8x16[c] + 8, 8);
    }
}

/* 显示字符串 */
void OLED_ShowString(uint8_t y, uint8_t x, char *str, uint8_t font_size)
{
    uint8_t i = 0;
    uint8_t char_width = (font_size == FONT_6x8) ? 6 : 8;
    
    while (str[i] != '\0')
    {
        if (x + char_width > 128)
        {
            x = 0;
            y += (font_size == FONT_6x8) ? 1 : 2;
        }
        if (y >= 8) break;
        
        OLED_ShowChar(y, x, str[i], font_size);
        x += char_width;
        i++;
    }
}

/* 显示数字（简化版） */
void OLED_ShowNum(uint8_t y, uint8_t x, float num, uint8_t len, uint8_t font_size)
{
    char buf[32];
    snprintf(buf, sizeof(buf), "%.*f", len, num);
    OLED_ShowString(y, x, buf, font_size);
}

/* ===== 16x16 汉字显示（2026-11-14 新增）=====
 *
 * 字模排布与 SSD1306 的 page 寻址直接对应：
 *   一个汉字 32 字节 = 上半 16 字节 + 下半 16 字节
 *   每字节是一列 8 个像素，bit0 在该页最上面
 * 所以画一个字只要两次"定位 + 连写 16 字节"，不用跨页拼接位图。
 * 写入目标是 RAM 显存，真正上屏由 OLED_Refresh() 统一做。
 */
void OLED_ShowCN(uint8_t y, uint8_t x, CnChar_t ch)
{
    if ((y > 6) || (x > (128 - 16))) return;   /* 越界直接丢弃，不去写坏别的区域 */
    if ((uint16_t)ch >= CN_CHAR_COUNT) return;

    OLED_SetPos(y, x);
    OLED_PutBytes((const uint8_t *)g_cn16x16[ch], 16);
    OLED_SetPos(y + 1, x);
    OLED_PutBytes((const uint8_t *)g_cn16x16[ch] + 16, 16);
}

/* 连续显示 n 个汉字，每字 16 px 宽，右边放不下就停。
 * 用例：OLED_ShowCNStr(0, 0, 2, CN_DIAN, CN_CHI);   // 屏幕左上角显示"电池" */
void OLED_ShowCNStr(uint8_t y, uint8_t x, uint8_t n, ...)
{
    va_list ap;
    uint8_t i;

    va_start(ap, n);
    for (i = 0; i < n; i++)
    {
        if (x > (128 - 16)) break;
        OLED_ShowCN(y, x, (CnChar_t)va_arg(ap, int));
        x += 16;
    }
    va_end(ap);
}

