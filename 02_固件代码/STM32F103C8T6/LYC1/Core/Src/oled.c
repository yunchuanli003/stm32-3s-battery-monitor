/* 写入命令 */
static void OLED_WriteCmd(uint8_t cmd)
{
    uint8_t buf[2] = {OLED_CMD, cmd};
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, 2, OLED_TIMEOUT);
}

/* 写入数据 */
static void OLED_WriteData(uint8_t *data, uint16_t len)
{
    uint8_t buf[129];
    buf[0] = OLED_DATA;
    memcpy(buf + 1, data, len);
    HAL_I2C_Master_Transmit(&hi2c1, OLED_I2C_ADDR, buf, len + 1, OLED_TIMEOUT);
}

/* 设置光标位置 */
void OLED_SetPos(uint8_t y, uint8_t x)
{
    OLED_WriteCmd(0xB0 + y);
    OLED_WriteCmd(((x & 0xF0) >> 4) | 0x10);
    OLED_WriteCmd(x & 0x0F);
}

/* 清屏 */
void OLED_Clear(void)
{
    uint8_t i, j;
    uint8_t buf[128] = {0};
    
    for (i = 0; i < 8; i++)
    {
        OLED_SetPos(i, 0);
        OLED_WriteData(buf, 128);
    }
}

/* OLED初始化 */
void OLED_Init(void)
{
    HAL_Delay(100);
    
    OLED_WriteCmd(0xAE); // 关闭显示
    
    OLED_WriteCmd(0x20); // 设置内存寻址模式
    OLED_WriteCmd(0x10); // 页面寻址模式
    
    OLED_WriteCmd(0xB0); // 设置页地址
    
    OLED_WriteCmd(0xC8); // COM扫描方向
    OLED_WriteCmd(0x00); // 列地址低位
    OLED_WriteCmd(0x10); // 列地址高位
    
    OLED_WriteCmd(0x40); // 设置起始行地址
    
    OLED_WriteCmd(0x81); // 设置对比度
    OLED_WriteCmd(0xFF);
    
    OLED_WriteCmd(0xA1); // 段重映射
    OLED_WriteCmd(0xA6); // 正常显示
    
    OLED_WriteCmd(0xA8); // 多路复用率
    OLED_WriteCmd(0x3F);
    
    OLED_WriteCmd(0xA4); // 显示全部开启
    
    OLED_WriteCmd(0xD3); // 显示偏移
    OLED_WriteCmd(0x00);
    
    OLED_WriteCmd(0xD5); // 显示时钟分频
    OLED_WriteCmd(0xF0);
    
    OLED_WriteCmd(0xD9); // 预充电周期
    OLED_WriteCmd(0x22);
    
    OLED_WriteCmd(0xDA); // COM引脚配置
    OLED_WriteCmd(0x12);
    
    OLED_WriteCmd(0xDB); // VCOMH
    OLED_WriteCmd(0x20);
    
    OLED_WriteCmd(0x8D); // 电荷泵
    OLED_WriteCmd(0x14);
    
    OLED_WriteCmd(0xAF); // 开启显示
    
    OLED_Clear();
}

/* 显示单个字符 */
void OLED_ShowChar(uint8_t y, uint8_t x, char ch, uint8_t font_size)
{
    uint8_t c = 0, i = 0;
    
    c = ch - ' ';
    
    if (font_size == FONT_6x8)
    {
        OLED_SetPos(y, x);
        OLED_WriteData((uint8_t *)F6x8[c], 6);
    }
    else if (font_size == FONT_8x16)
    {
        OLED_SetPos(y, x);
        OLED_WriteData((uint8_t *)F8X16[c], 8);
        OLED_SetPos(y + 1, x);
        OLED_WriteData((uint8_t *)F8X16[c] + 8, 8);
    }
}

/* 显示字符串 */
void OLED_ShowString(uint8_t y, uint8_t x, char *str, uint8_t font_size)
{
    uint8_t i = 0;
    uint8_t char_width = (font_size == FONT_6x8) ? 6 : 8;
    
    while (str[i] != '\0')
    {
        if (x + char_width > 128)
        {
            x = 0;
            y += (font_size == FONT_6x8) ? 1 : 2;
        }
        if (y >= 8) break;
        
        OLED_ShowChar(y, x, str[i], font_size);
        x += char_width;
        i++;
    }
}

/* 显示数字（简化版） */
void OLED_ShowNum(uint8_t y, uint8_t x, float num, uint8_t len, uint8_t font_size)
{
    char buf[32];
    snprintf(buf, sizeof(buf), "%.*f", len, num);
    OLED_ShowString(y, x, buf, font_size);
}

